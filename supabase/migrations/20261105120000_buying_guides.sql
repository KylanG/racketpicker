## 2. Vergelijk de echte prijs

Een racket kan bij de ene winkel tientallen euro's meer kosten dan bij de andere, ook voor precies hetzelfde model. Vergelijk daarom altijd:

- **De prijs inclusief verzendkosten.** Veel padelwinkels versturen gratis vanaf een bepaald bedrag, maar niet allemaal.
- **De levertijd.** Een lage prijs met twee weken levertijd is niet altijd de beste keuze als je komend weekend wilt spelen.
- **De voorraad.** Een racket dat "op voorraad" staat, kan bij de ene winkel morgen in huis zijn en bij de andere pas na een week.

In het [overzicht van padelrackets](/nl/rackets/padel) zie je per racket de laagste prijs bij Nederlandse winkels. Uitverkochte aanbiedingen staan nooit tussen de beschikbare. Hoe we aan onze prijzen komen en wat we verdienen, staat op [Hoe we verdienen](/nl/hoe-we-verdienen).

## 3. Is die korting echt?

Rond Black Friday en in de uitverkoop zie je veel doorgestreepte prijzen met hoge kortingspercentages. Volgens de regels moet de korting worden berekend op de **laagste prijs die de winkel in de 30 dagen ervoor rekende**. Een winkel mag dus niet eerst de prijs verhogen en daarna "korting" geven. De ACM heeft webwinkels die dat toch deden boetes gegeven.

Let ook op woorden als "adviesprijs" of "normaal". Dat is niet altijd een prijs die de winkel zelf ooit gerekend heeft. Bij veel padelrackets ligt de adviesprijs ver boven wat je er in de praktijk voor betaalt. "50% korting" op de adviesprijs is dan niet bijzonder.

Wij tonen een korting alleen als die klopt met de prijshistorie die we zelf bijhouden. Hoe dat werkt, lees je op [Prijshistorie](/nl/prijshistorie).

## 4. Pas op voor namaak

Populaire rackets, vooral de topmodellen van de grote merken, worden nagemaakt. Een namaakracket lijkt van buiten soms sprekend op het echte, maar het materiaal binnenin is van veel lagere kwaliteit. Het speelt anders en gaat vaak snel kapot.

Signalen om op te letten:

- **De prijs is veel te mooi.** Een nieuw topmodel voor een fractie van wat andere winkels vragen, is verdacht.
- **Onbekende webwinkel zonder gegevens.** Kijk of er een adres, een KvK-nummer, een klantenservice en duidelijke voorwaarden op de site staan. Een KvK-nummer alleen zegt overigens nog niet alles.
- **Alleen verkoop via social media of marktplaatsen.** Daar is het lastiger om te controleren wie de verkoper is.
- **Geen of vreemde reviews.** Kijk bij een onafhankelijke reviewsite, niet alleen naar de reviews op de winkelsite zelf.

Koop je via een groot platform zoals bol, kijk dan wie de **verkoper** is. Dat is lang niet altijd het platform zelf; vaak verkoopt een andere winkel via het platform. Je bestelt dan bij die partner, en bij problemen ligt de afhandeling vaak bij hem.

## 5. Bedenktijd en garantie

Koop je online, dan heb je bij bijna alle aankopen **14 dagen bedenktijd**. Je mag het racket dan zonder reden terugsturen. Je moet binnen 14 dagen laten weten dat je het niet houdt, en daarna heb je nog eens 14 dagen om het terug te sturen. De winkel moet je het aankoopbedrag, inclusief de oorspronkelijke verzendkosten, terugbetalen. De kosten van het terugsturen zijn vaak voor jezelf, als de winkel dat vooraf duidelijk heeft vermeld.

Let op: tijdens de bedenktijd mag je het product bekijken en uitproberen zoals je in een winkel ook zou doen. Een racket waarmee je al een paar wedstrijden hebt gespeeld, kan de winkel minder waard vinden. Speel dus niet met een racket dat je misschien terug wilt sturen.

Gaat een racket kapot zonder dat je er iets geks mee hebt gedaan? Dan geldt de **wettelijke garantie**: een product moet zo lang meegaan als je redelijkerwijs mag verwachten. Daarvoor ga je naar de **verkoper**, niet naar de fabrikant. Normale slijtage, zoals krassen op de rand of een versleten grip, valt er niet onder. Schade door een klap tegen de muur of het hek meestal ook niet.

Sommige merken of winkels geven daarnaast een eigen garantie. Lees dan wat die precies dekt: vaak gaat het om fabrieksfouten in de eerste maanden.

## 6. Test als het kan

Een racket voelt pas echt na een half uur op de baan. Veel padelwinkels hebben testrackets die je kunt lenen of op de baan kunt proberen, soms tegen een kleine vergoeding die je terugkrijgt als je koopt. Ook bij veel padelbanen kun je rackets huren.

Weet je het gewicht precies? Rackets van hetzelfde model kunnen een paar gram van elkaar verschillen. Sommige winkels laten je een racket met een specifiek gewicht uitzoeken of kunnen dat voor je regelen.

## Kort samengevat

1. Kies eerst het type racket dat bij je spel past, en kijk dan pas naar prijzen.
2. Vergelijk de prijs inclusief verzendkosten, levertijd en voorraad.
3. Een korting is pas echt als die lager is dan de laagste prijs van de afgelopen 30 dagen.
4. Wantrouw een veel te lage prijs bij een onbekende verkoper.
5. Je hebt online 14 dagen bedenktijd, en wettelijke garantie bij de verkoper.
6. Test als het kan, en kijk ook naar het model van vorig jaar.


  $md$## Wat een beginner echt nodig heeft

In je eerste maanden padel leer je vooral de bal op tijd raken, je positie op de baan vinden en de muren gebruiken. Een racket helpt daar het meest bij als het **vergevingsgezind** is: ook een bal die je niet precies in het midden raakt, komt nog redelijk terug over het net.

Dat betekent in de praktijk:

- **Vorm:** rond of druppel. De sweet spot is groter en zit lager dan bij een diamant.
- **Gewicht:** licht tot gemiddeld, ongeveer 345–365 gram. Je houdt het een hele avond vol en je arm wordt niet overbelast.
- **Balans:** laag of midden. Het racket draait makkelijk en voelt lichter aan.
- **Kern:** zacht. De bal komt makkelijk van het racket af, zonder dat je hard hoeft te slaan.
- **Slagvlak:** glasvezel of zacht carbon. Dat is flexibeler en vergevingsgezinder dan een stijf carbon slagvlak.

Een racket voor gevorderden is niet "beter" voor een beginner. Het is vaak harder, kopzwaarder en kleiner in de sweet spot. Je mist dan meer ballen, je hebt sneller last van je arm en je leert de slagen moeilijker aan.

## Hoeveel moet je uitgeven?

Je hoeft als beginner geen topmodel van € 300 of meer te kopen. Dat geld steek je beter in lessen of baanhuur. Rackets voor beginners en recreanten zijn er vanaf een paar tientjes. De topmodellen van de grote merken kosten bij hun introductie vaak € 300 tot € 400, maar worden later in het seizoen of na de komst van een nieuw jaarmodel vaak flink goedkoper.

Een paar vuistregels:

- **Onder de € 75:** prima om te ontdekken of padel iets voor je is. Let op de vorm en de hardheid, niet alleen op de prijs.
- **€ 75–150:** hier vind je veel goede rackets voor beginners en spelers op middenniveau.
- **Boven de € 150:** zinvol als je vaak speelt en weet wat je wilt. Kijk dan ook naar het vorige jaarmodel van hetzelfde racket.


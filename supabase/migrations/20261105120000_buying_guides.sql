## Waar beginners vaak de mist in gaan

**Het racket van een profspeler kopen.** De rackets van topspelers zijn gemaakt voor hun spel: veel kracht, hoge balans en een harde kern. Voor een beginner is dat vooral lastig. Kijk naar het niveau dat de fabrikant opgeeft.

**Alleen op korting kopen.** Een hoge korting op een racket dat niet bij je past, is geen goede deal. Kijk ook of de korting echt is: een doorgestreepte prijs moet volgens de regels de laagste prijs van de afgelopen 30 dagen zijn. Meer daarover lees je in [Padelracket kopen: waar let je op?](/nl/blog/padelracket-kopen-waar-let-je-op).

**Te zwaar beginnen.** Een zwaarder racket voelt in de winkel stevig, maar na anderhalf uur spelen merk je het in je onderarm. Twijfel je tussen twee gewichten, kies dan de lichtere.

**Je arm negeren.** Heb je eerder last gehad van je elleboog of pols, bijvoorbeeld van tennis? Kies dan een zachte kern, een lage balans en een niet te zwaar racket. Gaan klachten niet over, laat je dan adviseren door een fysiotherapeut.

## Huren, lenen of proberen

Veel padelbanen verhuren rackets. Dat is een goede manier om verschillende vormen te proberen voordat je zelf iets koopt. Ook veel padelwinkels hebben testrackets die je voor een klein bedrag kunt lenen of op de baan kunt uitproberen. Soms trekken ze dat bedrag weer af als je het racket koopt.

Let bij het proberen vooral op hoe het voelt na een half uur spelen, niet na drie slagen.


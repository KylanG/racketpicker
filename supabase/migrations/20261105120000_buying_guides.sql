  $md$## Eerst: hoe vaak en hoe speel je?

Voordat je naar vormen en grammen kijkt, helpt het om eerlijk te zijn over je eigen spel. Speel je een keer per week voor de lol, of train je en speel je competitie? Sta je vooral achterin en verdedig je, of zoek je het net op om af te maken? En heb je weleens last van je elleboog of pols?

Die antwoorden bepalen meer dan het merk of de prijs. Een racket dat bij een toernooispeler past, kan voor een recreant juist te zwaar, te hard en te veeleisend zijn. Andersom geldt dat ook: wie al jaren speelt, groeit vaak uit een heel vergevingsgezind racket.

## De vorm: rond, druppel of diamant

De vorm van de kop bepaalt vooral waar de **sweet spot** zit: de plek op het slagvlak waar je de bal het best raakt.

- **Rond:** de sweet spot zit laag en in het midden, en is relatief groot. Het racket voelt licht in de hand en is vergevingsgezind als je de bal niet precies raakt. Goed voor controle, verdedigen en voor wie net begint.
- **Druppel (teardrop):** de tussenvorm. De sweet spot zit iets hoger, waardoor je wat meer kracht krijgt zonder veel controle in te leveren. Veel spelers op middenniveau en allrounders kiezen deze vorm.
- **Diamant:** de sweet spot zit hoog in de kop en het gewicht ligt meer naar boven. Dat geeft veel kracht bij de smash en de bandeja, maar het racket is minder vergevingsgezind en vraagt meer techniek en kracht in je arm.

Er bestaan ook **hybride** of geometrische vormen, zoals de [Bullpadel Neuron 02 Edge](/nl/rackets/padel?merk=bullpadel). Die zitten meestal tussen druppel en diamant in. Kijk bij zulke modellen vooral naar de balans en de hardheid, want "hybride" betekent per merk iets anders.

Twijfel je? Dan is een druppelvorm voor de meeste spelers een veilige keuze.

## Gewicht: lichter is niet altijd beter

De meeste padelrackets voor volwassenen wegen ergens tussen de 340 en 385 gram. Fabrikanten geven vaak een bereik op, zoals 360–375 gram, omdat rackets van hetzelfde model van elkaar kunnen verschillen.

- **Lichter** (onder ongeveer 355 gram) draait sneller, is makkelijker bij het net en belast je arm minder bij lange sessies. Je levert wel wat stabiliteit en doorslag in.
- **Gemiddeld** (ongeveer 355–365 gram) is voor de meeste volwassen spelers een goed beginpunt.
- **Zwaarder** (boven ongeveer 365 gram) voelt stabieler en geeft meer kracht, maar wordt na een lange wedstrijd vermoeiend als je techniek nog niet zuinig is.

In het [overzicht van padelrackets](/nl/rackets/padel) kun je filteren op licht, gemiddeld en zwaar. Die indeling gebruikt het midden van het bereik dat de fabrikant opgeeft.

## Balans: waar zit het gewicht?

Twee rackets van precies hetzelfde gewicht kunnen heel anders aanvoelen. Dat komt door de **balans**: het punt waar het racket in evenwicht is, gemeten vanaf de onderkant van de grip.

- **Lage balans:** het gewicht zit dichter bij je hand. Het racket voelt lichter dan het is, draait snel en is fijn voor verdedigen en volleren. Een voorbeeld is de [Wilson Endure Pro V1](/nl/rackets/padel?merk=wilson).
- **Middenbalans:** een neutraal gevoel en een goed compromis. Bij veel druppelrackets ligt de balans hier.
- **Hoge balans (kopzwaar):** het gewicht zit naar de kop toe. Dat geeft meer kracht bij overhead-slagen, maar ook meer belasting op je pols, elleboog en schouder. Dit zie je vooral bij diamantrackets, zoals de [Adidas Metalbone Pro EDT](/nl/rackets/padel?merk=adidas).

Sommige rackets hebben een verstelbaar gewichtssysteem met kleine gewichtjes in de grip of de kop. Daarmee kun je de balans iets verschuiven. Handig, maar het maakt een racket dat niet bij je past niet ineens passend.

## De kern: zacht of hard

Binnen in het racket zit een kern van schuim, meestal **EVA** of een zachter schuim (foam).

- **Zacht:** de bal zakt iets dieper in het slagvlak. Dat geeft comfort en makkelijke kracht bij rustige slagen, en het is vriendelijker voor je arm.
- **Hard:** het racket reageert directer en geeft meer controle en snelheid bij harde slagen, maar je moet zelf meer kracht leveren en je voelt meer trillingen.

Merken gebruiken eigen namen voor hun schuim (Soft Performance, MultiEVA, HR3 en zo verder). Die zijn onderling lastig te vergelijken. Kijk liever naar wat de fabrikant over het gevoel zegt (zacht, gemiddeld, hard) en naar de beschrijving bij het racket zelf.

## Het slagvlak: glasvezel of carbon

- **Glasvezel** is flexibeler en vergevingsgezinder. Je vindt het vooral bij rackets voor beginners en in het lagere prijssegment.
- **Carbon** is stijver en geeft een directere, krachtigere bal. De getallen (3K, 12K, 18K) zeggen iets over de weving van de vezels. Hoe dat precies voelt, verschilt per merk. Een hoger getal betekent dus niet automatisch "beter".

Een ruw of 3D-oppervlak geeft wat meer grip op de bal en dus meer spin. Een glad oppervlak geeft een voorspelbaarder gevoel.

## Wat zegt het reglement?

De internationale padelfederatie FIP legt de maximale maten vast: een racket mag in totaal hoogstens 45,5 cm lang zijn, 26 cm breed en 38 mm dik, en de grip hoogstens 20 cm lang. Een polskoord is verplicht. Gewicht en balans zijn vrij. Daarom lopen die tussen modellen zo uiteen.

